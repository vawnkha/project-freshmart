const router = require("express").Router();
const auth = require("../middlewares/auth.middleware");
const validate = require("../middlewares/validate.middleware");
const schema = require("../validators/expiry.validator");
const controller = require("../controllers/expiry.controller");
router.use(auth, auth.authorizePermissions("admin:access"));
const inventory = auth.authorizePermissions("inventory:manage");
const discounts = auth.authorizePermissions("discount:manage");
router.get("/summary", inventory, controller.summary);
router.get("/batches", inventory, validate({ query: schema.list }), controller.list);
router.get("/batches/:id", inventory, validate({ params: schema.id }), controller.detail);
router.patch("/batches/:id/expiry-date", inventory, validate({ params: schema.id, body: schema.correction }), controller.correctExpiry);
router.get("/batches/:id/recommendation", inventory, validate({ params: schema.id }), controller.recommendation);
router.post("/batches/:id/promotion-proposals", inventory, validate({ params: schema.id, body: schema.create }), controller.create);
router.get("/promotion-proposals", discounts, validate({ query: schema.proposals }), controller.proposals);
router.patch("/promotion-proposals/:id", inventory, validate({ params: schema.id, body: schema.edit }), controller.update);
router.post("/promotion-proposals/:id/approve", discounts, validate({ params: schema.id, body: schema.approve }), controller.approve);
router.post("/promotion-proposals/:id/reject", discounts, validate({ params: schema.id, body: schema.reject }), controller.reject);
router.post("/promotion-proposals/:id/cancel", discounts, validate({ params: schema.id }), controller.cancel);
module.exports = router;
